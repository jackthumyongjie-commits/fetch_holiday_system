  detect: function () {
    try {
      var saved = localStorage.getItem(this.storageKey);
      if (saved && this.strings[saved]) {
        return saved;
      }
    } catch (err) {}
    var nav = (navigator.language || 'en').toLowerCase();
    if (nav.indexOf('zh') === 0) return 'zh';
    if (nav.indexOf('ms') === 0 || nav.indexOf('id') === 0) return 'ms';
    return 'en';
  },

  save: function (lang) {
    try {
      localStorage.setItem(this.storageKey, lang);
    } catch (err) {}
  },

  t: function (lang, key) {
    var pack = this.strings[lang] || this.strings.en;
    if (pack[key] !== undefined) return pack[key];
    return this.strings.en[key] || key;
  },

  holidayName: function (holiday, lang) {
    if (lang === 'zh') return holiday.name_zh;
    if (lang === 'ms') return holiday.name_ms;
    return holiday.name_en;
  },

  holidayDesc: function (holiday, lang) {
    if (lang === 'zh') return holiday.description_zh || '';
    if (lang === 'ms') return holiday.description_ms || '';
    return holiday.description_en || '';
  },

  typeLabel: function (lang, type) {
    var map = {
      federal: this.t(lang, 'typeFederal'),
      state: this.t(lang, 'typeState'),
      birthday: this.t(lang, 'typeBirthday'),
      observance: this.t(lang, 'typeObservance')
    };
    return map[type] || type;
  },

  formatDate: function (dateStr, lang) {
    var parts = dateStr.split('-');
    var months = this.t(lang, 'months');
    var monthName = months[parseInt(parts[1], 10) - 1] || parts[1];
    return parseInt(parts[2], 10) + ' ' + monthName + ' ' + parts[0];
  },

  translateStates: function (states, lang) {
    if (!states) return this.t(lang, 'nationwide');
    var dict = this.t(lang, 'states');
    return states.split(',').map(function (item) {
      var name = item.trim();
      return dict[name] || name;
    }).join(', ');
  },

  apply: function (lang) {
    document.documentElement.lang = lang === 'ms' ? 'ms' : (lang === 'zh' ? 'zh-Hans' : 'en');
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var value = window.CutiI18n.t(lang, key);
      if (typeof value === 'string') el.textContent = value;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      el.setAttribute('placeholder', window.CutiI18n.t(lang, el.getAttribute('data-i18n-placeholder')));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', window.CutiI18n.t(lang, el.getAttribute('data-i18n-aria')));
    });
    var titleKey = document.body.getAttribute('data-title-key');
    if (titleKey) {
      document.title = 'Cuti MY – ' + window.CutiI18n.t(lang, titleKey);
    }
  }
